// Records every Chaos Console line with Kokoro (free, open-source, runs on this computer, no account or key)
// and saves it to voices/<id>.mp3, then rewrites voices/manifest.js.
// Lines that already have a file are skipped, so you can stop and re-run it any time (and only edited lines get re-recorded).
//
// First time only, inside this scripts folder:   npm install
//
//   node generate-voices.mjs --dry-run      count lines, record nothing
//   node generate-voices.mjs --sample 6     record only the first 6 lines, to audition the voices
//   node generate-voices.mjs                record everything that is missing
//   node generate-voices.mjs --force        re-record everything (after changing a voice)
//   node generate-voices.mjs --prune        also delete recordings no line uses any more
//   node generate-voices.mjs --pluto am_puck --theory bm_lewis    try other Kokoro voices
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import os from "node:os";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const flag = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const dryRun = args.includes("--dry-run");
const force = args.includes("--force");
const sample = args.includes("--sample") ? Number(flag("--sample")) || 6 : Infinity;
const outDir = path.resolve(root, flag("--out", "voices"));

const VOICES = {
  P: { voice: flag("--pluto", "am_puck"), speed: 1.05 }, // Pluto: bright, playful American
  T: { voice: flag("--theory", "bm_george"), speed: 0.95 } // Theory: dry, unbothered British
};

// Must match lineId() in characters.js.
const lineId = (who, text) => {
  let h = 0x811c9dc5;
  for (const c of `${who}|${text}`) { h ^= c.codePointAt(0); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, "0");
};
// Same clean-up as the browser voice: no emoji, "Sooooo" -> "Soo", SHOUTED words read as words, not spelled out.
const spoken = (t) => t
  .replace(/\p{Extended_Pictographic}|\u{FE0F}/gu, "")
  .replace(/([a-z])\1{2,}/gi, "$1$1")
  .replace(/\b[A-Z]{2,}\b/g, (w) => (/^(TED|PR|AI|OK|HR)$/.test(w) ? w : w.toLowerCase()))
  .replace(/[“”]/g, '"').replace(/[‘’]/g, "'")
  .replace(/\s+/g, " ").trim();

const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "conversation.js"), "utf8"), ctx);
const lines = new Map();
for (const scene of Object.values(ctx.window.PT_SCENES))
  for (const l of scene.lines)
    if (/[a-z]/i.test(l.t)) lines.set(lineId(l.s, l.t), { who: l.s, text: spoken(l.t) });

fs.mkdirSync(outDir, { recursive: true });
const exists = (id) => fs.existsSync(path.join(outDir, `${id}.mp3`));
const todo = [...lines].filter(([id]) => force || !exists(id)).slice(0, sample);
console.log(`${lines.size} unique lines, ${todo.length} to record. Pluto: ${VOICES.P.voice}, Theory: ${VOICES.T.voice}.`);

function writeManifest() {
  const have = [...lines.keys()].filter(exists).sort();
  // The version is the newest recording time: it changes only when clips are re-recorded, telling browsers to fetch them again.
  const version = Math.floor(Math.max(0, ...have.map((id) => fs.statSync(path.join(outDir, `${id}.mp3`)).mtimeMs))).toString(36);
  fs.writeFileSync(path.join(outDir, "manifest.js"),
    `// Generated by scripts/generate-voices.mjs. Lists the recorded chat lines in this folder.\nwindow.PT_VOICE_VERSION = "${version}";\nwindow.PT_VOICE_FILES = {${have.map((id) => `"${id}":1`).join(",")}};\n`);
  return have.length;
}
// --prune deletes recordings that no current line uses (left over after lines are edited).
if (args.includes("--prune")) {
  const stale = fs.readdirSync(outDir).filter((f) => f.endsWith(".mp3") && !lines.has(f.slice(0, -4)));
  stale.forEach((f) => fs.unlinkSync(path.join(outDir, f)));
  console.log(`Removed ${stale.length} unused recordings.`);
}
if (dryRun || !todo.length) { writeManifest(); process.exit(0); }

const { KokoroTTS } = await import("kokoro-js");
// Keep the model in a short path: the voice engine cannot open files in very long Windows paths.
(await import("@huggingface/transformers")).env.cacheDir = path.join(os.homedir(), ".cache", "kokoro-voices");
const { Mp3Encoder } = await import("@breezystack/lamejs");
console.log("Loading the Kokoro voice model (downloads about 90 MB the first time)…");
const tts = await KokoroTTS.from_pretrained("onnx-community/Kokoro-82M-v1.0-ONNX", { dtype: "q8", device: "cpu" });

function toMp3(samples, rate) {
  // Kokoro pads every line with ~0.3 s of silence at the start and ~0.2 s at the end, which reads as a delay
  // on the site. Find where speech starts and stops (10 ms windows), keep a short breath either side,
  // bring every line to the same loudness so Pluto and Theory match, then encode mono 64 kbps.
  const win = Math.round(rate * 0.01), rms = [];
  for (let i = 0; i < samples.length; i += win) {
    let s = 0; const end = Math.min(samples.length, i + win);
    for (let j = i; j < end; j++) s += samples[j] * samples[j];
    rms.push(Math.sqrt(s / (end - i)));
  }
  const first = Math.max(0, rms.findIndex((v) => v > 0.01));
  const last = Math.max(first, rms.findLastIndex((v) => v > 0.01));
  const from = Math.max(0, (first - 3) * win), to = Math.min(samples.length, (last + 9) * win);
  const speech = samples.subarray(from, to);
  let sum = 0, peak = 0;
  for (const v of speech) { sum += v * v; peak = Math.max(peak, Math.abs(v)); }
  const gain = Math.min(0.12 / (Math.sqrt(sum / speech.length) || 1), 0.95 / (peak || 1)); // target loudness, never clip
  const pcm = new Int16Array(speech.length);
  for (let i = 0; i < pcm.length; i++) pcm[i] = Math.max(-1, Math.min(1, speech[i] * gain)) * 32767;
  const enc = new Mp3Encoder(1, rate, 64), out = [];
  for (let i = 0; i < pcm.length; i += 1152) out.push(enc.encodeBuffer(pcm.subarray(i, i + 1152)));
  out.push(enc.flush());
  return Buffer.concat(out.map((b) => Buffer.from(b.buffer, b.byteOffset, b.length)));
}

let done = 0;
for (const [id, { who, text }] of todo) {
  const audio = await tts.generate(text, VOICES[who]);
  fs.writeFileSync(path.join(outDir, `${id}.mp3`), toMp3(audio.audio, audio.sampling_rate));
  console.log(`[${++done}/${todo.length}] ${who}: ${text.slice(0, 60)}`);
}
console.log(`Manifest updated: ${writeManifest()} of ${lines.size} lines have audio.`);
